let n1 = prompt("Digite o primeiro numero: ");
let n2 = prompt("Digite o segundo numero: ");

let soma = parseFloat(n1) + parseFloat(n2);
let sub = parseFloat(n1) - parseFloat(n2);
let prod = parseFloat(n1) * parseFloat(n2);
let div = parseFloat(n1) / parseFloat(n2);
let rest = parseFloat(n1) % parseFloat(n2);

alert("Soma: " + soma);
alert("Subtraçao: " + sub);
alert("Produto: " + prod);
alert("Divisao: " + div);
alert("Resto: " + rest);